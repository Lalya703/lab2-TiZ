# Критерий 3: поиск по совпадению слов; сортировка TOP-5; сохранение ID; пустой запрос.
import numpy as np

TOP = 5  # сколько документов возвращаем на запрос


def base_search(query_words, doc_words, ids, k=TOP):
    """Базовый поиск без TF-IDF: чем больше РАЗНЫХ слов запроса есть в документе, тем он выше.

    query_words - список слов запроса после обработки (Человек 2);
    doc_words   - список документов, каждый документ - список его слов;
    ids         - document_id в том же порядке, что и doc_words;
    Возвращает [(document_id, число совпавших слов)] - не больше k штук.
    """
    # set: повтор слова в запросе не должен давать лишний балл
    q = set(query_words)

    # Пустой запрос (например, остались одни стоп-слова): искать нечего,
    # возвращаем пустой список, а не случайные документы с нулевым счётом.
    if not q:
        return []

    # Счёт документа = размер пересечения множеств слов запроса и документа.
    # Частота слова в документе здесь НЕ учитывается - это отличие от TF-IDF.
    sc = np.array([len(q & set(d)) for d in doc_words], dtype=float)

    # Сортируем по убыванию счёта (минус перед sc). kind="stable" сохраняет
    # порядок документов в корпусе при равных счётах, поэтому результат
    # одинаков при каждом запуске.
    order = np.argsort(-sc, kind="stable")[:k]

    # Документы с нулевым совпадением в выдачу не берём: они не релевантны.
    # В ответе сохраняем document_id, а не номер строки.
    return [(ids[i], float(sc[i])) for i in order if sc[i] > 0]
