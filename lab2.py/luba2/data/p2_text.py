def stem(w):
    """Простая замена лемматизации, если pymorphy3 не установлен: отрезаем окончание"""
    for e in ENDS:
        if w.endswith(e) and len(w) - len(e) >= 3:
            return w[: -len(e)]
    return w


def make_lem():
    """pymorphy3, если установлен; иначе простой стеммер. Кэш ускоряет работу"""
    try:
        import pymorphy3
        morph = pymorphy3.MorphAnalyzer()
        one = lambda w: morph.parse(w)[0].normal_form
    except ImportError:
        print("pymorphy3 не найден: используется простой стеммер")
        one = stem
    cache = {}

    def lem(w):
        if w not in cache:
            cache[w] = one(w)
        return cache[w]
    return lem


def words(text):
    """Очистка и токенизация: все в нижний регистр, ё -> е, только буквы и цифры"""
    text = str(text).lower().replace("ё", "е")
    return re.findall(r"[a-zа-я0-9]+", text)


def prep(text, lem, use_lem, drop_stop):
    """Одна и та же обработка для документов и запросов"""
    ws = words(text)
    if drop_stop:
        ws = [w for w in ws if w not in STOP]
    if use_lem:
        ws = [lem(w) for w in ws]
        if drop_stop:  # стоп-слова могут появиться и после лемматизации
            ws = [w for w in ws if w not in STOP]
    return ws


def full_text(docs):
    """Текст для индексации: заголовок + основной текст"""
    return (docs["title"].fillna("") + ". " + docs["text"].fillna("")).tolist()
